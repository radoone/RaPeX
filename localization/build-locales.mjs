// Deterministic local generation only. No translation service, credentials or network calls.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = dirname(fileURLToPath(import.meta.url));
const languages = JSON.parse(await readFile(resolve(dir, 'languages.json'), 'utf8'));
const emails = {};
function leaves(object, prefix = '') {
  return Object.fromEntries(Object.entries(object).flatMap(([key, value]) => {
    const path = prefix ? `${prefix}.${key}` : key;
    return typeof value === 'object' && value !== null ? Object.entries(leaves(value, path)) : [[path, value]];
  }));
}
const source = JSON.parse(await readFile(resolve(dir, 'catalogs/en.json'), 'utf8'));
const expected = leaves(source);
for (const { code } of languages) {
  const catalog = JSON.parse(await readFile(resolve(dir, `catalogs/${code}.json`), 'utf8'));
  const values = leaves(catalog);
  if (JSON.stringify(Object.keys(expected).sort()) !== JSON.stringify(Object.keys(values).sort())) throw new Error(`Missing/extra translation keys: ${code}`);
  for (const [key, value] of Object.entries(values)) {
    if (typeof value !== 'string' || !value.trim()) throw new Error(`Empty translation ${code}:${key}`);
    const tokens = text => (text.match(/\{\{[^}]+\}\}/g) || []).sort().join('|');
    if (tokens(value) !== tokens(expected[key])) throw new Error(`Interpolation mismatch ${code}:${key}`);
  }
  await writeFile(resolve(dir, `../marketing-site/locales/${code}.json`), JSON.stringify(catalog.web, null, 2) + '\n');
  emails[code] = catalog.email;
}
await writeFile(resolve(dir, '../firebase/functions/src/email-locales.ts'), '// Generated by localization/build-locales.mjs from committed catalogs.\nexport const EMAIL_LOCALES: Record<string, Record<string, string>> = ' + JSON.stringify(emails, null, 2) + ';\n');
console.log(`Generated web and email catalogs for ${languages.length} EU languages.`);
